def summarize_data(input_df, run_data_size = 100000000):
    prompt = """现给定一些投诉内容和该投诉是否下派。请总结下派/不下派的投诉单中，是否存在共性特征。你总结的共性特征，将作为用于判断投诉内容是否下派的依据。\n\n"""
    data_size = min(len(input_df), run_data_size)
    for i in range(data_size):
        row_data = input_df.iloc[i]
        pending_content = row_data['抽取内容']
        to_assign = row_data['主单是否下派']
        piece_prompt = f"投诉内容：{pending_content}，是否下派：{to_assign}\n\n"
        prompt += piece_prompt
    return prompt

