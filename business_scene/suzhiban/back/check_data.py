"""
根据对所有投诉单的整理，下派与不下派的投诉共性特征总结如下：

### 一、不下派投诉的共性特征
不下派投诉整体符合「可通过现有标准化流程/线上自助渠道处理，无特殊复杂场景，无超出规范的特殊诉求」的核心特点，具体共性：
1. **诉求仅为简单的不认可停机、要求尽快处理/复机，无额外特殊要求**：大量仅表述「对号码被封停不认可，要求尽快处理」的标准化诉求、没有补充特殊场景/未解决矛盾的投诉，均为不下派。
2. **用户符合现有免下派的处理规则**：
   - 用户可通过线上自助/指定营业厅完成复机，只是因自身原因（人在外地/身份证不在身边/不方便去营业厅/不愿自助操作）暂时无法完成，没有出现规则外的例外情况；
   - 已经按照规范完成解释引导，用户仍不认可但无新的未解决矛盾；
   - 同名下号码本自然年内复机次数已达上限，不符合再次复机的规范要求。
3. **无特殊紧急场景或复杂历史遗留问题**：不存在卡丢失、多次复机失败、营业厅/自助渠道处理不成功、前期已处理但未解决、有赔偿/投诉工作人员/费用争议等额外问题，仅为基础停机诉求。
4. **停机前状态特殊，实际未停机**：比如仅收到停机提醒短信、号码当前仍处于在用状态，还未实际执行停机。

---

### 二、下派投诉的共性特征
下派投诉整体符合「现有标准化流程无法解决，存在特殊场景/未解决的历史问题/超出常规的紧急诉求，需要线下介入核实处理」的核心特点，具体共性：
1. **存在标准化流程无法解决的特殊场景**：
   - 特殊身份/证件问题：使用护照等非居民身份证登记、机主是高龄老人/在境外/国外，无法按常规流程完成复机；
   - 实体卡异常：手机卡丢失、补卡和复机流程冲突（补卡需要先复机，复机需要验证卡）、ICCID识别不通过，无法走常规自助流程；
   - 渠道处理失败：已经通过线上自助、比邻柜台、线下营业厅尝试复机，但均操作不成功，无法解决问题。
2. **存在未解决的历史遗留/复合问题**：
   - 已经按流程处理过一次（甚至多次），问题仍未解决，用户再次来电投诉；
   - 除了复机诉求外，还有额外诉求：比如要求退还停机期间的费用、赔偿停机损失、投诉工作人员服务态度问题、要求解释停机的具体原因（不认可通用解释）、要求更改实际使用人、要求退订业务等复合诉求；
   - 实际使用人离职、找不到实际使用人完成认证，或机主和实际使用人分离，用户代诉求无法通过常规流程处理。
3. **存在特殊紧急需求**：用户明确说明有紧急使用场景（比如要坐飞机、急需用号码办公、身处机场等紧急场景），要求限时处理，常规流程无法满足用户的时效要求。
4. **存在特殊风险/需要线下核实的情况**：停机原因异常（比如函件双停、公安停机、工信部断卡单停等特殊停机类型），或用户明确提出对停机原因不认可，要求核查具体原因、提供停机证据，需要线下核实后回复。
5. **用户明确有越级投诉倾向**：用户已经表示如果不处理就向工信部投诉，需要加急跟进处理。
"""
def judge_assign_or_not(complaint_content):
    judge_assign_prompt = f"""根据给定的下派和不下派投诉单的共性特征，判断给定的投诉内容是否需要下派。你只需要输出下派/不下派，不需要输出其它任何信息。
    投诉内容为：{complaint_content}
共同特征为：
### 一、不下派投诉单的共性特征
1. **基础场景共性**
超过6成不下派投诉都属于**线上电子渠道办理业务不及时/不成功，且核实后订单流水未关联到订单、号码状态正常在用**的场景，这类投诉仅需核查订单关联问题，没有超出当前坐席可处理范围的特殊矛盾。
2. **诉求特征共性**
    - 仅单纯要求核查线上订单未关联的原因，无额外复杂诉求、没有对已有解释/处理方案的不认可；
    - 属于规则明确、可直接在线解释答复的问题：如国际漫游开通受卡类型限制、权益补领规则不支持补领、部分业务必须线下营业厅办理用户不认可、老年人不会操作仅需指导无需线下处理；
    - 诉求为退费退订，但不符合退费规则（如一年内已有退费记录、翼支付券过期要求退费），仅需解释无需下派；
    - 仅为操作类问题（如不会取消业务、不会开通、找不到办理入口），无需线下/专人现场处理；
    - 无具体投诉内容、无明确可处理诉求，仅需登记无需下派。
3. **矛盾程度共性**
用户没有明确的不认可、没有越级投诉倾向，也不存在久拖未决的遗留问题，矛盾程度较低。

把属于xxx特征的数据整理出来，人工去抽检。


---

### 二、下派投诉单的共性特征
1. **核心触发特征**
几乎所有下派投诉都存在**用户对已有解释/处理结果不认可，或者业务办理本身已经出现明确的错误、久拖未解决**的情况，具体包括：
    - 线上办理业务失败，同时存在额外的实体业务/费用矛盾：如保证金到期未解冻、宽带移机申请后长期无人联系、套餐承诺优惠未兑现、资费争议（多扣费、错扣费）、宽带速率不达标、业务开通与告知不符、拆机后余额/押金不退等；
    - 用户不认可现有规则/处理方案：不认可必须去营业厅办理的要求、不认可收费标准、不认可停拆机结果、不认可业务办理限制，已经过在线解释仍不接受，需要专人跟进；
    - 存在遗留问题：之前反馈的问题未答复、未解决，用户再次来电催单，或者存在多个问题未处理完毕；
    - 诉求需要线下落地处理：如宽带复装、移机上门、销户、过户、线下业务审批、设备故障处理等，必须属地工作人员对接完成；
    - 存在升级投诉风险：用户明确表示要向工信部/通管局投诉，或者要求限时答复处理，已有在线解释无法安抚用户；
    - 涉及历史遗留的特殊问题：比如固话信息不明、旧业务押金不退、欠费争议影响用户权益，需要专人核实历史信息处理。
2. **场景延伸特征**
即便是同样存在「线上订单流水未关联」的基础场景，只要叠加了上述需要专人核实、线下处理、用户不认可的情况，都会下派处理。
"""
    return query_doubao(judge_assign_prompt, 200)

